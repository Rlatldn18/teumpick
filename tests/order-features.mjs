import assert from 'node:assert/strict';
import { salesRange, koreaDate } from '../app/sales-period.ts';
import { orderEvents } from '../app/order-events.ts';
const day = salesRange('2026-09-05', 'day');
assert.equal(new Date(day.start).toISOString(), '2026-09-04T15:00:00.000Z');
assert.equal(day.end - day.start, 86400000);
assert.equal(koreaDate(Date.parse('2026-09-04T15:00:00Z')), '2026-09-05');
assert.equal(salesRange('2026-09-06', 'week').label, '2026-08-31 ~ 2026-09-06');
assert.equal(salesRange('2026-09-07', 'week').label, '2026-09-07 ~ 2026-09-13');
assert.equal(salesRange('2024-02-15', 'month').end - salesRange('2024-02-15', 'month').start, 29 * 86400000);
assert.equal(salesRange('2026-12-31', 'year').label, '2026-01-01 ~ 2026-12-31');
const order = { id: 'test', status: 0, menuName: '덮밥', shopName: '매장', qty: 2, total: 19000, station: '신도림', locker: 1 };
assert.equal(orderEvents([order], 'seller', new Set()).length, 1);
assert.equal(orderEvents([order], 'buyer', new Set()).length, 0);
assert.equal(orderEvents([order], 'seller', new Set(['test:0'])).length, 0);
assert.equal(orderEvents([{...order, status: 3}], 'buyer', new Set())[0].title, '지금 픽업해 주세요!');
assert.equal(orderEvents([{...order, status: 4}], 'buyer', new Set()).length, 0);
assert.equal(orderEvents([{...order, status: 5, canceledBy: 'seller'}], 'buyer', new Set()).length, 1);
assert.equal(orderEvents([{...order, status: 5, canceledBy: 'buyer'}], 'buyer', new Set()).length, 0);
assert.equal(orderEvents([{...order, status: 5, canceledBy: 'seller'}], 'buyer', new Set(['test:5'])).length, 0);
console.log('PASS: KST day/week/month/year boundaries, leap year, role-specific and once-acknowledged order popups.');
